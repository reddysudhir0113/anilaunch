/**
 * Notification Context for AniLaunch
 * Manages in-app notifications, floating toasts, browser permissions, and active interval checks.
 */

import React, { createContext, useContext, useState, useEffect, useCallback } from 'react';
import {
  getStoredNotifications,
  saveStoredNotifications,
} from '../services/localStorage';
import {
  runReminderCheck,
  requestBrowserNotificationPermission,
  getBrowserNotificationPermission,
} from '../services/notificationService';
import { useAnime } from './AnimeContext';

const NotificationContext = createContext(null);

export function NotificationProvider({ children }) {
  const { animeList, settings } = useAnime();
  const [notifications, setNotifications] = useState(() => getStoredNotifications());
  const [toasts, setToasts] = useState([]);
  const [permissionStatus, setPermissionStatus] = useState(() => getBrowserNotificationPermission());

  // Keep LocalStorage in sync when notifications update
  useEffect(() => {
    saveStoredNotifications(notifications);
  }, [notifications]);

  /**
   * Adds an in-app toast
   */
  const addToast = useCallback((toast) => {
    const id = `toast_${Date.now()}_${Math.random().toString(36).substr(2, 6)}`;
    const newToast = {
      id,
      title: toast.title || 'Notification',
      message: toast.message || '',
      type: toast.type || 'info', // info, success, warning, launch
      duration: toast.duration || 5000,
    };

    setToasts((prev) => [...prev, newToast]);

    if (newToast.duration > 0) {
      setTimeout(() => {
        setToasts((prev) => prev.filter((t) => t.id !== id));
      }, newToast.duration);
    }
  }, []);

  /**
   * Removes a specific toast
   */
  const removeToast = useCallback((id) => {
    setToasts((prev) => prev.filter((t) => t.id !== id));
  }, []);

  /**
   * Handles new notification generated by background checker
   */
  const handleNewNotification = useCallback((notif) => {
    setNotifications((prev) => [notif, ...prev].slice(0, 50));
    addToast({
      title: notif.title,
      message: notif.message,
      type: 'launch',
    });
  }, [addToast]);

  /**
   * Active reminder checking timer (every 25 seconds while tab is open)
   */
  useEffect(() => {
    // Initial check
    runReminderCheck(animeList, settings, handleNewNotification);

    const interval = setInterval(() => {
      runReminderCheck(animeList, settings, handleNewNotification);
    }, 25000);

    return () => clearInterval(interval);
  }, [animeList, settings, handleNewNotification]);

  /**
   * Request native browser permission
   */
  const requestPermission = useCallback(async () => {
    const status = await requestBrowserNotificationPermission();
    setPermissionStatus(status);
    if (status === 'granted') {
      addToast({
        title: 'Notifications Enabled! 🚀',
        message: 'You will receive launch alerts for upcoming episodes while AniLaunch is open.',
        type: 'success',
      });
    } else if (status === 'denied') {
      addToast({
        title: 'Notifications Blocked',
        message: 'Browser permissions were denied. You can still see in-app alerts.',
        type: 'warning',
      });
    }
    return status;
  }, [addToast]);

  /**
   * Marks a notification as read
   */
  const markAsRead = useCallback((id) => {
    setNotifications((prev) =>
      prev.map((n) => (n.id === id ? { ...n, isRead: true } : n))
    );
  }, []);

  /**
   * Marks all notifications as read
   */
  const markAllAsRead = useCallback(() => {
    setNotifications((prev) => prev.map((n) => ({ ...n, isRead: true })));
  }, []);

  /**
   * Clears notification history
   */
  const clearNotifications = useCallback(() => {
    setNotifications([]);
  }, []);

  const unreadCount = notifications.filter((n) => !n.isRead).length;

  return (
    <NotificationContext.Provider
      value={{
        notifications,
        unreadCount,
        toasts,
        permissionStatus,
        addToast,
        removeToast,
        markAsRead,
        markAllAsRead,
        clearNotifications,
        requestPermission,
      }}
    >
      {children}
    </NotificationContext.Provider>
  );
}

export function useNotifications() {
  const context = useContext(NotificationContext);
  if (!context) {
    throw new Error('useNotifications must be used within a NotificationProvider');
  }
  return context;
}
